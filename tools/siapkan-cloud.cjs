function bacaEnv() {
  return Object.fromEntries(
    fs.readFileSync(ENV, 'utf8').split(/\r?\n/)
      .filter((l) => l.includes('=') && !l.startsWith('#'))
      .map((l) => { const i = l.indexOf('='); return [l.slice(0, i), l.slice(i + 1)]; }),
  );
}

(async () => {
  /* 1. Cadangan lokal dulu (aturan E1) */
  const folder = 'c:/data/UangKu/data/backups';
  fs.mkdirSync(folder, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 16);
  fs.copyFileSync(SUMBER, path.join(folder, `uangku-${stamp}-sebelum-siapkan-cloud.db`));
  console.log(`Cadangan lokal: uangku-${stamp}-sebelum-siapkan-cloud.db`);

  const env = bacaEnv();
  const owner = env.LB_OWNER_URL.match(/^postgresql:\/\/([^:]+):([^@]+)@/);
  if (!owner) throw new Error('LB_OWNER_URL tidak terbaca di .env');

  const sqlite = new D(SUMBER, { readonly: true, fileMustExist: true });
  const pg = new Client({
    host: HOST, port: 5432, user: owner[1], password: owner[2],
    database: 'uangku', ssl: { rejectUnauthorized: false },
  });
  await pg.connect();

  /* 2. Periksa skema tujuan */
  const ada = await pg.query(
    'SELECT 1 FROM information_schema.schemata WHERE schema_name = $1', [SKEMA],
  );
  if (ada.rowCount > 0) {
    if (!ULANG) {
      console.log(`\n⚠️  Skema "${SKEMA}" SUDAH ADA. Tidak ada yang diubah.`);
      console.log('   Kalau memang mau dibuat ulang dari nol: node tools\\siapkan-cloud.cjs --ulang');
      sqlite.close(); await pg.end(); process.exit(0);
    }
    console.log(`\nSkema "${SKEMA}" lama dihapus (--ulang)...`);
    await pg.query(`DROP SCHEMA "${SKEMA}" CASCADE`);
  }

  await pg.query(`CREATE SCHEMA "${SKEMA}"`);
  console.log(`Skema "${SKEMA}" dibuat.\n`);

  /* 3. Buat tabel + salin baris */
  const hasil = [];
  for (const t of URUTAN) {
    await pg.query(DDL[t]);

    const kol = sqlite.prepare(`PRAGMA table_info("${t}")`).all();
    const baris = sqlite.prepare(`SELECT * FROM "${t}"`).all();
    const nama = kol.map((k) => `"${k.name}"`).join(',');

    const per = Math.max(1, Math.min(500, Math.floor(BATAS_PARAM / kol.length)));
    for (let i = 0; i < baris.length; i += per) {
      const blok = baris.slice(i, i + per);
      const nilai = [];
      const param = [];
      blok.forEach((r) => {
        const ph = kol.map((k) => {
          param.push(r[k.name] === undefined ? null : r[k.name]);
          return '$' + param.length;
        });
        nilai.push('(' + ph.join(',') + ')');
      });
      await pg.query(`INSERT INTO "${SKEMA}"."${t}" (${nama}) VALUES ${nilai.join(',')}`, param);
    }

    const ditulis = Number((await pg.query(`SELECT COUNT(*) n FROM "${SKEMA}"."${t}"`)).rows[0].n);
    hasil.push({ t, dibaca: baris.length, ditulis, cocok: baris.length === ditulis });
  }

  /* 3b. 🔴 PENTING — setel ulang penomoran otomatis.
        Baris disalin dengan id eksplisit, jadi penomoran PostgreSQL masih di 1
        → baris BARU akan bentrok ("duplicate key"). Setelah ini, id baru = max(id)+1. */
  for (const t of URUTAN) {
    await pg.query(
      `SELECT setval(pg_get_serial_sequence('"${SKEMA}"."${t}"', 'id'), ` +
      `COALESCE((SELECT MAX(id) FROM "${SKEMA}"."${t}"), 0) + 1, false)`,
    );
  }
  console.log('Penomoran otomatis disetel ulang untuk ' + URUTAN.length + ' tabel.\n');

  /* 4. Sidik jari saldo — bandingkan SQLite vs PostgreSQL
        ⚠️ SQLite pakai `?`, PostgreSQL pakai `$1..$4` — jangan tertukar */
  const saldoSql = (ph, awalan) => `
    SELECT f.id, f.name,
      COALESCE(s.saldo_awal, 0)
      + COALESCE(SUM(CASE WHEN j.type = 'D' THEN t.amount ELSE 0 END), 0)
      - COALESCE(SUM(CASE WHEN j.type = 'K' THEN t.amount ELSE 0 END), 0) AS saldo
    FROM ${awalan}source_funds f
    LEFT JOIN ${awalan}monthly_snapshots s ON s.source_fund_id = f.id AND s.year = ${ph[0]} AND s.month = ${ph[1]}
    LEFT JOIN ${awalan}transactions t ON t.source_fund_id = f.id
      AND t.date >= ${ph[2]} AND t.date <= ${ph[3]} AND t.deleted_at IS NULL
      AND COALESCE(t.is_historical, 0) = 0
    LEFT JOIN ${awalan}journals j ON j.id = t.journal_id
    WHERE f.deleted_at IS NULL
    GROUP BY f.id, f.name, s.saldo_awal
    ORDER BY f.id`;

  const bulan = sqlite.prepare(
    "SELECT MAX(substr(date,1,7)) b FROM transactions WHERE deleted_at IS NULL AND is_historical=0",
  ).get().b;
  const [th, bl] = bulan.split('-').map(Number);
  const akhir = new Date(Date.UTC(th, bl, 0)).getUTCDate();
  const dari = `${bulan}-01`;
  const sampai = `${bulan}-${String(akhir).padStart(2, '0')}`;

  const saldoSqlite = sqlite.prepare(saldoSql(['?', '?', '?', '?'], '')).all(th, bl, dari, sampai);
  const saldoPg = (await pg.query(saldoSql(['$1', '$2', '$3', '$4'], `"${SKEMA}".`), [th, bl, dari, sampai])).rows;

  sqlite.close();
  await pg.end();

  /* 5. Laporan */
  console.log('=== JUMLAH BARIS ===');
  for (const h of hasil) {
    console.log(`${h.cocok ? 'OK  ' : 'BEDA'} ${h.t.padEnd(20)} sqlite=${String(h.dibaca).padStart(5)}  cloud=${String(h.ditulis).padStart(5)}`);
  }

  console.log(`\n=== SIDIK JARI SALDO (${bulan}) ===`);
  let beda = 0;
  for (let i = 0; i < saldoSqlite.length; i++) {
    const a = Number(saldoSqlite[i].saldo);
    const b = Number(saldoPg[i].saldo);
    const sama = Math.abs(a - b) < 0.005;
    if (!sama) beda++;
    console.log(`${sama ? 'OK  ' : 'BEDA'} ${String(saldoSqlite[i].name).padEnd(20)} sqlite=${a.toFixed(2).padStart(16)}  cloud=${b.toFixed(2).padStart(16)}`);
  }

  const gagalBaris = hasil.filter((h) => !h.cocok).length;
  console.log(
    gagalBaris === 0 && beda === 0
      ? `\n✅ SELESAI — ${hasil.length} tabel, semua jumlah baris cocok, ${saldoSqlite.length} saldo fund identik (skema "${SKEMA}")`
      : `\n⚠️  ${gagalBaris} tabel beda baris · ${beda} saldo fund beda — PERIKSA DULU`,
  );
  process.exit(gagalBaris === 0 && beda === 0 ? 0 : 1);
})().catch((e) => { console.error('GALAT:', e.message); process.exit(1); });
